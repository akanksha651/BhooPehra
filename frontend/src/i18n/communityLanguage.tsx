function isLanguage(value: string | null): value is CommunityLanguage {
  return (
    value === "English" ||
    value === "Hindi" ||
    value === "Assamese" ||
    value === "Mizo" ||
    value === "Bengali"
  )
}

export function getCommunityLanguage(): CommunityLanguage {
  try {
    const value = window.localStorage.getItem(COMMUNITY_LANGUAGE_KEY)
    return isLanguage(value) ? value : DEFAULT_LANGUAGE
  } catch {
    return DEFAULT_LANGUAGE
  }
}

export function setCommunityLanguage(language: CommunityLanguage) {
  try {
    window.localStorage.setItem(COMMUNITY_LANGUAGE_KEY, language)
  } catch {
    // Keep the current page functional even if storage is unavailable.
  }

  window.dispatchEvent(
    new CustomEvent(COMMUNITY_LANGUAGE_EVENT, {
      detail: language,
    }),
  )
}

function normalizeTranslationText(text: string): string {
  return text
    .replace(/\s+/g, " ")
    .trim()
    .replace(/[.。!?！？]+$/u, "")
    .toLowerCase()
}

function translateByDictionary(
  language: CommunityLanguage,
  text: string,
): string {
  const dictionary = {
    ...translations[language],
    ...EXTRA_TRANSLATIONS[language],
    ...COMMUNITY_COMPLETE_TRANSLATIONS[language],
    ...COMMUNITY_SURFACE_PATCH[language],
  }
  const exact = dictionary[text] ?? dictionary[text.trim()]

  if (exact) {
    return exact
  }

  const normalized = normalizeTranslationText(text)
  if (!normalized) {
    return text
  }

  const normalizedEntries = Object.entries(dictionary)
    .map(([source, target]) => ({
      source,
      target,
      normalizedSource: normalizeTranslationText(source),
    }))
    .filter((entry) => entry.normalizedSource.length >= 4)
    .sort((a, b) => b.normalizedSource.length - a.normalizedSource.length)

  const phrase = normalizedEntries.find((entry) =>
    normalized.includes(entry.normalizedSource),
  )

  if (phrase) {
    const sourceIndex = text.toLowerCase().indexOf(
      phrase.source.toLowerCase(),
    )

    if (sourceIndex >= 0) {
      return (
        text.slice(0, sourceIndex) +
        phrase.target +
        text.slice(sourceIndex + phrase.source.length)
      )
    }
  }

  return text
}

export function translate(
  language: CommunityLanguage,
  text: string,
): string {
  return translateByDictionary(language, text)
}

/**
 * Community-only localization bridge.
 *
 * Most BhooPehra operational pages are shared by multiple roles. Instead of
 * forcing every shared page to become multilingual for Authority/Field Team,
 * this bridge localizes the rendered Community surface only. It watches for
 * React-rendered text changes so API-loaded status messages are translated too.
 */
export function CommunityLanguageController() {
  const { role } = useRole()
  const { language } = useCommunityLanguage()
  const observerRef = useRef<MutationObserver | null>(null)
  const translatedRef = useRef(
    new WeakMap<Text, { source: string; translated: string }>(),
  )

  useEffect(() => {
    if (role !== "COMMUNITY" || typeof document === "undefined") {
      observerRef.current?.disconnect()
      observerRef.current = null
      return
    }

    const shouldSkipNode = (node: Text) => {
      const parent = node.parentElement
      if (!parent) return true

      const tag = parent.tagName.toLowerCase()
      return (
        tag === "script" ||
        tag === "style" ||
        tag === "noscript" ||
        parent.closest("svg") !== null ||
        parent.closest("code, pre") !== null
      )
    }

    const localizeTextNode = (node: Text) => {
      if (shouldSkipNode(node)) return

      const current = node.nodeValue ?? ""
      const trimmed = current.trim()
      if (!trimmed) return

      const previous = translatedRef.current.get(node)
      const source =
        previous && current === previous.translated
          ? previous.source
          : current

      const translated = translate(language, source)
      translatedRef.current.set(node, { source, translated })

      if (translated !== current) {
        node.nodeValue = translated
      }
    }

    const localizeAttributes = (element: Element) => {
      for (const attribute of ["placeholder", "aria-label", "title"]) {
        const value = element.getAttribute(attribute)
        if (!value?.trim()) continue

        const sourceMarker = `data-bp-i18n-source-${attribute}`
        const valueMarker = `data-bp-i18n-value-${attribute}`
        const previousSource = element.getAttribute(sourceMarker)
        const previousValue = element.getAttribute(valueMarker)
        const source =
          previousSource &&
          (value === previousValue || value === previousSource)
            ? previousSource
            : value
        const translated = translate(language, source)

        element.setAttribute(sourceMarker, source)
        element.setAttribute(valueMarker, translated)
        if (translated !== value) {
          element.setAttribute(attribute, translated)
        }
      }
    }

    const localizeTree = (root: Node) => {
      const walker = document.createTreeWalker(
        root,
        NodeFilter.SHOW_TEXT,
      )

      let node = walker.nextNode() as Text | null
      while (node) {
        localizeTextNode(node)
        node = walker.nextNode() as Text | null
      }

      if (root instanceof Element) {
        localizeAttributes(root)
        root.querySelectorAll("*").forEach(localizeAttributes)
      }
    }

    localizeTree(document.body)

    const observer = new MutationObserver((mutations) => {
      observer.disconnect()
      for (const mutation of mutations) {
        if (mutation.type === "characterData" && mutation.target instanceof Text) {
          localizeTextNode(mutation.target)
        }

        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE && node instanceof Text) {
            localizeTextNode(node)
          } else if (node.nodeType === Node.ELEMENT_NODE) {
            localizeTree(node)
          }
        })

        if (mutation.type === "attributes" && mutation.target instanceof Element) {
          localizeAttributes(mutation.target)
        }
      }
      observer.observe(document.body, {
        subtree: true,
        childList: true,
        characterData: true,
        attributes: true,
        attributeFilter: ["placeholder", "aria-label", "title"],
      })
    })

    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["placeholder", "aria-label", "title"],
    })
    observerRef.current = observer

    return () => {
      observer.disconnect()
      observerRef.current = null
    }
  }, [language, role])

  return null
}

export function useCommunityLanguage() {
  const [language, setLanguageState] =
    useState<CommunityLanguage>(DEFAULT_LANGUAGE)

  useEffect(() => {
    setLanguageState(getCommunityLanguage())

    const handleLanguageChange = (event: Event) => {
      const customEvent = event as CustomEvent<CommunityLanguage>
      const next = customEvent.detail

      if (isLanguage(next)) {
        setLanguageState(next)
      } else {
        setLanguageState(getCommunityLanguage())
      }
    }

    const handleStorage = (event: StorageEvent) => {
      if (event.key === COMMUNITY_LANGUAGE_KEY) {
        setLanguageState(getCommunityLanguage())
      }
    }

    window.addEventListener(COMMUNITY_LANGUAGE_EVENT, handleLanguageChange)
    window.addEventListener("storage", handleStorage)

    return () => {
      window.removeEventListener(
        COMMUNITY_LANGUAGE_EVENT,
        handleLanguageChange,
      )
      window.removeEventListener("storage", handleStorage)
    }
  }, [])

  const setLanguage = useCallback((next: CommunityLanguage) => {
    setCommunityLanguage(next)
    setLanguageState(next)
  }, [])

  const t = useCallback(
    (text: string) => translate(language, text),
    [language],
  )

  return {
    language,
    setLanguage,
    t,
  }
}
